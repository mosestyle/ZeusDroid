#!/usr/bin/env python3
"""Embed the eZeus sanctuary layouts (eZeus source repo, folder sanctuaries/,
GPL-3 like the engine) into the engine, so sanctuaries work without the
eZeus data pack's Sanctuaries/ folder (Android never imports it).

Usage: embed_blueprints.py <ezeus-source>/sanctuaries > engine/buildings/sanctuaries/esanctuaryblueprintdata.inc
"""
import os
import sys

src = sys.argv[1]
print('// Generated by tools/sanctuaries/embed_blueprints.py from the eZeus')
print('// source repository (sanctuaries/*.txt, GPL-3). Do not edit by hand.')
print('static const std::pair<const char*, const char*> gSanctBlueprintData[] = {')
for name in sorted(os.listdir(src)):
    if not name.endswith('.txt'):
        continue
    with open(os.path.join(src, name), encoding='ascii') as f:
        text = f.read().replace('\r\n', '\n').replace('\r', '\n').strip('\n')
    print('    {"%s",' % name)
    for line in text.split('\n'):
        print('     "%s\\n"' % line.rstrip())
    print('    },')
print('};')
