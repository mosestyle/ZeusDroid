#!/usr/bin/env python3
"""Writes engine/texbuild/etexmap.inc from build/texbuild/texmap.json (made by
texmap_gen.py). The table holds only sprite indices and crop offsets."""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
m = json.load(open(os.environ.get('TEXMAP_JSON', os.path.join(ROOT, 'build/texbuild/texmap.json'))))
split = open(os.path.join(ROOT, 'engine/esplitbinary.h')).read()
iface = set(re.findall(r'"30/([A-Za-z0-9_]+)_\d+\.png", eBinaryData\{eFileId::i,', split))


def var(path):
    t = open(path).read()
    g = re.search(r'const auto (\w+) = std::vector<eSpriteData>', t)
    return g.group(1) if g else None


out = ['// Generated by tools/texbuild/texmap_emit.py - do not edit.',
       '// Atlas frame -> original sprite (record index in DATA/<file>.sg3, crop',
       '// offset). Indices only; the pixels come from the user\'s own files.', '']
rows = []
file_ids = {}
all_atlases = sorted(set(re.findall(r'"30/([A-Za-z0-9_]+)_\d+\.png"', split)))
missing = []
for name in all_atlases:
    e = m.get(name)
    if e is None:
        # No original source found: written as transparent pages so the game
        # still finds every image name.
        n = len(re.findall(r'eSpriteData\{', open(os.path.join(ROOT, 'engine/spriteData', f'{name}30.h')).read()))
        e = {'file': '', 'frames': [None]*n}
        missing.append(name)
    vars_ = []
    ok = True
    for s in (15, 30, 45, 60):
        p = os.path.join(ROOT, 'engine/spriteData', f'{name}{s}.h')
        if not os.path.exists(p):
            ok = False
            break
        out.append(f'#include "spriteData/{name}{s}.h"')
        vars_.append(var(p))
    if not ok or None in vars_:
        continue
    fr = []
    for f in e['frames']:
        if f is None:
            fr.append('{-1,-1,0,0,0}')
            continue
        if e.get('v3'):
            fname, idx, cx, cy, sh = f[0], f[1], f[2], f[3], f[4]
        else:
            if f[1] < 0:
                fr.append('{-1,-1,0,0,0}')
                continue
            fname, idx, cx, cy, sh = e['file'], f[0], f[1], f[2], 1
        if fname not in file_ids:
            file_ids[fname] = len(file_ids)
        fr.append('{%d,%d,%d,%d,%d}' % (file_ids[fname], idx, cx, cy, sh))
    out.append(f'static const eTexMapFrame kTMF_{name}[] = {{' + ','.join(fr) + '};')
    rows.append('    {"%s", %s, kTMF_%s, %d, {&%s, &%s, &%s, &%s}},' % (
        name, 'true' if name in iface else 'false', name, len(fr), *vars_))
out.append('')
out.append('static const char* const kTexFiles[] = {' + ', '.join('"%s"' % f for f in file_ids) + '};')
out.append('static const int kTexFileCount = %d;' % len(file_ids))
jpgs = re.findall(r'\{"(\d+)/Zeus_Data_Images/([^"]+)", eBinaryData', split)
out.append('// Full-screen pictures (DATA/*.jpg): size, file name.')
out.append('static const eTexJpg kTexJpgs[] = {' + ','.join('{%s,"%s"}' % j for j in jpgs) + '};')
out.append('static const int kTexJpgCount = %d;' % len(jpgs))
out.append('static const eTexMapAtlas kTexMap[] = {')
out += rows
out.append('};')
out.append('static const int kTexMapCount = sizeof(kTexMap)/sizeof(kTexMap[0]);')
open(os.path.join(ROOT, 'engine/texbuild/etexmap.inc'), 'w').write('\n'.join(out) + '\n')
print(len(rows), 'atlases,', len(missing), 'without source:', ' '.join(missing))
